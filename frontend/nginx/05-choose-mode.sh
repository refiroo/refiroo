#!/bin/sh
# Picks the server configuration the image's entrypoint then fills from the environment (0.12 DP2).
set -eu

# True when $1 is an address or a range (a.b.c.d, a.b.c.d/n, or the IPv6 forms) nginx can trust.
valid_cidr() {
  address=${1%%/*}
  case $1 in */*) prefix=${1#*/}; ranged=1 ;; *) prefix=; ranged=0 ;; esac
  case $address in
    *:*)
      printf '%s' "$address" | grep -Eq '^[0-9A-Fa-f:.]+$' || return 1
      max=128 ;;
    *)
      printf '%s' "$address" | grep -Eq '^[0-9]{1,3}(\.[0-9]{1,3}){3}$' || return 1
      for octet in $(printf '%s' "$address" | tr . ' '); do
        [ "$octet" -le 255 ] || return 1
      done
      max=32 ;;
  esac
  if [ "$ranged" = 1 ]; then
    printf '%s' "$prefix" | grep -Eq '^[0-9]{1,3}$' || return 1
    [ "$prefix" -le "$max" ] || return 1
  fi
}

# WEB_TLS=proxy: the caller is the address nginx is connected from, unless that address is one of
# WEB_TRUSTED_PROXIES (a comma-separated list of addresses or ranges, empty by default: trust nobody),
# in which case the caller is the last address in X-Forwarded-For that is not itself trusted.
# envsubst cannot loop, so the list becomes `set_real_ip_from` lines in a file the template includes.
trust_proxies() {
  snippets=/etc/nginx/conf.d/snippets
  mkdir -p "$snippets"
  {
    echo "# Generated by 05-choose-mode.sh from WEB_TRUSTED_PROXIES; do not edit."
    echo "real_ip_header X-Forwarded-For;"
    echo "real_ip_recursive on;"
  } > "$snippets/real-ip.inc"
  set -f
  old_ifs=$IFS
  IFS=,
  for entry in ${WEB_TRUSTED_PROXIES:-}; do
    IFS=$old_ifs
    entry=$(printf '%s' "$entry" | tr -d ' \t')
    if [ -n "$entry" ]; then
      if ! valid_cidr "$entry"; then
        echo "web: WEB_TRUSTED_PROXIES has '$entry', which is not an address or a range." >&2
        echo "web: Write addresses or ranges separated by commas, for example 10.0.0.0/8,192.168.1.5,fd00::/8." >&2
        exit 1
      fi
      echo "set_real_ip_from $entry;" >> "$snippets/real-ip.inc"
    fi
    IFS=,
  done
  IFS=$old_ifs
  set +f
}

case "${WEB_TLS:-files}" in
  files)
    if [ ! -r /certs/fullchain.pem ] || [ ! -r /certs/privkey.pem ]; then
      echo "web: WEB_TLS=files needs /certs/fullchain.pem and /certs/privkey.pem (the organisation's certificate and key)." >&2
      echo "web: Mount them, or set WEB_TLS=proxy when a load balancer in front ends HTTPS." >&2
      exit 1
    fi
    template=tls.conf.template ;;
  proxy) template=proxy.conf.template; trust_proxies ;;
  *)
    echo "web: WEB_TLS must be 'files' or 'proxy', not '${WEB_TLS}'." >&2
    exit 1 ;;
esac
: "${PUBLIC_URL:?web: PUBLIC_URL, the address people open (for example https://rdm.example.org), is not set.}"

cp "/etc/nginx/templates-available/$template" /etc/nginx/templates/default.conf.template
echo "web: serving $PUBLIC_URL (WEB_TLS=${WEB_TLS:-files}), engine at $ENGINE_UPSTREAM"
